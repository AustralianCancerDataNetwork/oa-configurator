"""File I/O helpers: environment file export and TOML config persistence."""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

import tomli_w

from .loader import CONFIG_PATH, _normalize_path, invalidate_cache
from .resolver import Resolver
from .stack_config import StackConfig

logger = logging.getLogger(__name__)
FLAT_ENV_PATH = CONFIG_PATH.with_suffix(".env")


def write_env_file(resolver: Resolver, path: Path = FLAT_ENV_PATH) -> Path:
    """Write a flat KEY=VALUE file from the active resolved config.

    Written to *path* (default ``~/.config/omop/config.env``) for use with
    Docker Compose ``env_file:``.

    Naming convention
    -----------------
    - Database ``<name>`` connection → ``<NAME>_DB_{DIALECT,HOST,PORT,USER,PASSWORD,DATABASE_NAME,URL}``
    - Tool ``<name>`` scalar extra fields → ``<NAME>_{KEY}``

    All database names and tool names are uppercased with hyphens replaced by
    underscores.

    Deliberately covers connections/databases and tool extras only, not
    providers/models. This file exists to bootstrap the *other* services a
    Docker Compose stack starts (e.g. the ``postgres`` image needs its own
    ``environment:`` block before the Python app can even read
    ``config.toml``); LLM providers have no such bootstrapping need, since
    only the Python app itself ever calls one, always by reading
    ``config.toml`` directly through :class:`~oa_configurator.Resolver`.
    """
    path = _normalize_path(path)
    lines: list[str] = [
        "# Generated by `omop-config export-env`. Do NOT edit by hand.",
        "# Source of truth: ~/.config/omop/config.toml",
        "",
    ]

    for database_name in resolver.config.databases:
        prefix = f"{database_name.upper().replace('-', '_')}_DB"
        try:
            resolved = resolver.resolve_database(database_name)
            conn = resolver.get_connection(resolved.connection.name)
        except Exception as exc:
            logger.warning("Skipping database %r in env export: %s", database_name, exc)
            continue

        lines.extend(conn.to_env_pairs(prefix))
        lines.append(f"{prefix}_URL={resolved.connection.url}")
        lines.append("")

    for tool_name in resolver.config.tools:
        prefix = tool_name.upper().replace("-", "_")
        try:
            tool = resolver.resolve_tool(tool_name)
        except Exception as exc:
            logger.warning("Skipping tool %r in env export: %s", tool_name, exc)
            continue
        wrote_any = False
        for k, v in tool.extra.items():
            if isinstance(v, (str, int, float, bool)):
                lines.append(f"{prefix}_{k.upper()}={v}")
                wrote_any = True
        if wrote_any:
            lines.append("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def save_stack_config(config: StackConfig, path: Path = CONFIG_PATH) -> Path:
    """Serialize a :class:`~oa_configurator.stack_config.StackConfig` back to TOML.

    Does NOT preserve comments or original formatting. The ``logging`` section
    is omitted when it equals the default (no custom logging configured).

    TODO: adopt ``tomlkit`` for round-trip serialisation that preserves comments
    and original ordering.
    """
    from .logging_config import LoggingConfig

    path = _normalize_path(path)
    payload = _drop_none_and_empty(config.model_dump(mode="python"))
    if config.logging == LoggingConfig():
        payload.pop("logging", None)

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(tomli_w.dumps(payload), encoding="utf-8")
    invalidate_cache()
    return path


def _drop_none_and_empty(value: Any) -> Any:
    """Recursively strip None values and empty dicts from a model_dump result."""
    if isinstance(value, dict):
        cleaned = {k: _drop_none_and_empty(v) for k, v in value.items() if v is not None}
        return {k: v for k, v in cleaned.items() if v != {}}
    if isinstance(value, list):
        return [_drop_none_and_empty(v) for v in value]
    return value
