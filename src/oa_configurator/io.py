"""Helpers for reading and writing flat KEY=VALUE environment files."""

from __future__ import annotations

from pathlib import Path

from .resolver import Resolver

FLAT_ENV_PATH = Path("~/.config/omop/config.env").expanduser()

# Mapping: resource_name → env var prefix for CDM connection fields.
# Only resources listed here are exported; others are silently skipped.
_RESOURCE_ENV_PREFIX: dict[str, str] = {
    "default": "OMOP_CDM_DB",
    "omop_emb": "OMOP_EMB_DB",
}


def write_env_file(resolver: Resolver, path: Path = FLAT_ENV_PATH) -> Path:
    """Write a flat KEY=VALUE file from the active profile's resolved config.

    Written to ``path`` (default ``~/.config/omop/config.env``) for use with
    Docker Compose ``env_file:``.

    Mapping
    -------
    - Resource ``"default"`` primary_db → ``OMOP_CDM_DB_{HOST,PORT,USER,PASSWORD,NAME,DRIVER}`` + ``ENGINE``
    - Resource ``"omop_emb"`` primary_db → ``OMOP_EMB_DB_{HOST,PORT,...}``
    - Tool ``"omop_emb"`` ``extra.backend`` → ``OMOP_EMB_BACKEND``
    """
    lines: list[str] = [
        "# Generated by `omop-config export-env` — do not edit by hand.",
        "# Source of truth: ~/.config/omop/config.toml",
        "",
    ]

    for resource_name, env_prefix in _RESOURCE_ENV_PREFIX.items():
        if resource_name not in resolver.config.resources:
            continue
        try:
            resolved = resolver.resolve_resource(resource_name)
            conn = resolver._effective_connection(resolved.primary_db.name)
        except Exception:
            continue

        if conn.host:
            lines.append(f"{env_prefix}_HOST={conn.host}")
        if conn.port:
            lines.append(f"{env_prefix}_PORT={conn.port}")
        if conn.user:
            lines.append(f"{env_prefix}_USER={conn.user}")
        if conn.password:
            lines.append(f"{env_prefix}_PASSWORD={conn.password}")
        if conn.database:
            lines.append(f"{env_prefix}_NAME={conn.database}")
        if conn.dialect:
            lines.append(f"{env_prefix}_DRIVER={conn.dialect}")

        if resource_name == "default":
            lines.append(f"ENGINE={resolved.primary_db.url}")

        lines.append("")

    # Tool-specific extras
    if "omop_emb" in resolver.config.tools:
        try:
            tool = resolver.resolve_tool("omop_emb")
            backend = tool.extra.get("backend")
            if backend:
                lines.append(f"OMOP_EMB_BACKEND={backend}")
            lines.append("")
        except Exception:
            pass

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
